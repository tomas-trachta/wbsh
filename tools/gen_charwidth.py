#!/usr/bin/env python3
"""Generate wbshterm/src/charwidth_ucd.cpp from OpenConsole's width tables.

wbshterm's grid has to agree with the pseudoconsole on how many cells
every character takes, or the cursor drifts. The surest way to agree is
to use the very tables OpenConsole measures with, so this copies the
trie out of microsoft/terminal's src/types/CodepointWidthDetector.cpp
(MIT licensed) instead of deriving one from the Unicode data again.

    python tools/gen_charwidth.py path/to/CodepointWidthDetector.cpp
"""

import pathlib
import re
import sys

OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "wbshterm" / "src" / "charwidth_ucd.cpp"
PER_LINE = 10

HEADER = """/**
 * @file charwidth_ucd.cpp
 * @brief OpenConsole's width and grapheme-break trie, generated by tools/gen_charwidth.py.
 */

// Copied from microsoft/terminal, src/types/CodepointWidthDetector.cpp
// (Copyright (c) Microsoft Corporation, MIT license).
// Table generated {source}.
// Regenerate rather than edit.

#include "charwidth_ucd.h"

namespace wbshterm {{

	namespace ucd {{

"""

FOOTER = """
	} /* namespace ucd */

} /* namespace wbshterm */
"""


def array_values(source, name):
    match = re.search(r"static constexpr (\w+) " + name + r"(?:\[\d*\])+ = \{(.*?)\};", source,
                      re.S)
    if match is None:
        sys.exit("missing table " + name)
    return match.group(1), re.findall(r"0x[0-9a-fA-F]+|0b[01]+", match.group(2))


def emit_array(out, name, kind, values):
    out.append("\t\tconst std::{} {}[{}] = {{\n".format(kind, name, len(values)))
    for start in range(0, len(values), PER_LINE):
        out.append("\t\t\t" + ", ".join(values[start:start + PER_LINE]) + ",\n")
    out.append("\t\t};\n\n")


def emit_join_rules(out, values):
    rows = len(values) // 16
    out.append("\t\tconst std::uint32_t join_rules[{}][16] = {{\n".format(rows))
    for row in range(rows):
        out.append("\t\t\t{\n")
        for value in values[row * 16:(row + 1) * 16]:
            out.append("\t\t\t\t" + hex(int(value, 2)) + ",\n")
        out.append("\t\t\t},\n")
    out.append("\t\t};\n")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)

    source = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8")
    stamp = re.search(r"// Generated by GraphemeTableGen\s*\n// (.*)", source)

    out = [HEADER.format(source=stamp.group(1).strip() if stamp else "unknown version")]
    for stage in range(4):
        kind, values = array_values(source, "s_stage{}".format(stage))
        emit_array(out, "stage{}".format(stage), kind, values)

    _, rules = array_values(source, "s_joinRules")
    emit_join_rules(out, rules)
    out.append(FOOTER)

    OUTPUT.write_text("".join(out), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
