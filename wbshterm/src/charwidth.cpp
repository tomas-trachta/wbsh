/**
 * @file charwidth.cpp
 * @brief The width ranges, kept as sorted tables.
 */

#include "charwidth.h"

namespace wbshterm {

	struct CodeRange {
		char32_t first;
		char32_t last;
	};

	// Combining marks and joiners: they render on the previous cell.
	static const CodeRange kZeroWidth[] = {
		{ 0x0300, 0x036F }, { 0x0483, 0x0489 }, { 0x0591, 0x05BD }, { 0x0610, 0x061A },
		{ 0x064B, 0x065F }, { 0x0670, 0x0670 }, { 0x06D6, 0x06DC }, { 0x0730, 0x074A },
		{ 0x07A6, 0x07B0 }, { 0x0900, 0x0903 }, { 0x093A, 0x094F }, { 0x0951, 0x0957 },
		{ 0x0E31, 0x0E31 }, { 0x0E34, 0x0E3A }, { 0x0E47, 0x0E4E }, { 0x1AB0, 0x1AFF },
		{ 0x1DC0, 0x1DFF }, { 0x200B, 0x200F }, { 0x20D0, 0x20F0 }, { 0xFE00, 0xFE0F },
		{ 0xFE20, 0xFE2F }, { 0xE0100, 0xE01EF },
	};

	// East Asian Wide and Fullwidth, plus the emoji blocks that render
	// double-width in every terminal that gets this right.
	static const CodeRange kDoubleWidth[] = {
		{ 0x1100, 0x115F }, { 0x2E80, 0x303E }, { 0x3041, 0x33FF }, { 0x3400, 0x4DBF },
		{ 0x4E00, 0x9FFF }, { 0xA000, 0xA4CF }, { 0xA960, 0xA97F }, { 0xAC00, 0xD7A3 },
		{ 0xF900, 0xFAFF }, { 0xFE10, 0xFE19 }, { 0xFE30, 0xFE6F }, { 0xFF00, 0xFF60 },
		{ 0xFFE0, 0xFFE6 }, { 0x1F004, 0x1F004 }, { 0x1F0CF, 0x1F0CF }, { 0x1F18E, 0x1F18E },
		{ 0x1F191, 0x1F19A }, { 0x1F200, 0x1F320 }, { 0x1F32D, 0x1F335 }, { 0x1F337, 0x1F37C },
		{ 0x1F37E, 0x1F393 }, { 0x1F3A0, 0x1F3CA }, { 0x1F3CF, 0x1F3D3 }, { 0x1F3E0, 0x1F3F0 },
		{ 0x1F3F4, 0x1F3F4 }, { 0x1F3F8, 0x1F43E }, { 0x1F440, 0x1F440 }, { 0x1F442, 0x1F4FC },
		{ 0x1F4FF, 0x1F53D }, { 0x1F54B, 0x1F54E }, { 0x1F550, 0x1F567 }, { 0x1F57A, 0x1F57A },
		{ 0x1F595, 0x1F596 }, { 0x1F5A4, 0x1F5A4 }, { 0x1F5FB, 0x1F64F }, { 0x1F680, 0x1F6C5 },
		{ 0x1F6CC, 0x1F6CC }, { 0x1F6D0, 0x1F6D2 }, { 0x1F6EB, 0x1F6EC }, { 0x1F6F4, 0x1F6FC },
		{ 0x1F7E0, 0x1F7EB }, { 0x1F90C, 0x1F93A }, { 0x1F93C, 0x1F945 }, { 0x1F947, 0x1F9FF },
		{ 0x1FA70, 0x1FAFF }, { 0x20000, 0x2FFFD }, { 0x30000, 0x3FFFD },
	};

	static bool inRanges(char32_t code, const CodeRange* ranges, std::size_t count) {
		std::size_t low = 0;
		std::size_t high = count;

		while (low < high) {
			const std::size_t middle = low + (high - low) / 2;
			if (code < ranges[middle].first) high = middle;
			else if (code > ranges[middle].last) low = middle + 1;
			else return true;
		}

		return false;
	}

	int characterWidth(char32_t code) {
		if (code == 0) return 0;
		if (code < 0x0300) return 1;

		if (inRanges(code, kZeroWidth, sizeof(kZeroWidth) / sizeof(kZeroWidth[0]))) return 0;
		if (inRanges(code, kDoubleWidth, sizeof(kDoubleWidth) / sizeof(kDoubleWidth[0]))) return 2;
		return 1;
	}

} /* namespace wbshterm */
