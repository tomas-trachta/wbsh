	static std::string lowered(const std::string& text) {
		std::string out = text;
		std::transform(out.begin(), out.end(), out.begin(), [](unsigned char c) {
			return static_cast<char>(std::tolower(c));
		});
		return out;
	}

	bool findBuiltInTheme(const std::string& name, Palette& out_palette) {
		const std::string wanted = lowered(name);
		for (const NamedTheme& theme : kThemes) {
			if (lowered(theme.name) == wanted) {
				out_palette = theme.palette;
				return true;
			}
		}

		return false;
	}

	std::vector<std::string> builtInThemeNames() {
		std::vector<std::string> names;
		for (const NamedTheme& theme : kThemes) names.push_back(theme.name);
		return names;
	}

