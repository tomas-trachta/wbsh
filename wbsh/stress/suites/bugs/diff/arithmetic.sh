#!/bin/bash
# Arithmetic semantics.
echo $(( 7 / 2 )) $(( -7 / 2 )) $(( -7 % 3 )) $(( 7 % -3 )) $(( 2 ** 10 )) $(( 1 << 62 ))
echo $(( 0x1f )) $(( 017 )) $(( 2#1011 )) $(( 36#zz )) $(( 64#_ ))
echo $(( 5 > 3 && 2 > 1 )) $(( !0 )) $(( ~5 )) $(( 5 ^ 3 )) $(( 5 | 3 )) $(( 5 & 3 ))
i=5; echo $(( i++ )) $i $(( ++i )) $(( i-- )) $(( --i )) $i
echo $(( i += 3, i * 2 )) $i
echo $(( 1 ? 2 : 3 )) $(( 0 ? 2 : 3 )) $(( (1+2) * (3+4) ))
x=3+4; echo $(( x * 2 )) $(( $x * 2 ))
unset u; echo $(( u + 1 ))
a=(10 20 30); echo $(( a[1] + a[2] )) $(( ${#a[@]} * 2 ))
(( 0 )); echo $?
(( 5 )); echo $?
let 'z = 4 * 4' 'w = z + 1'; echo $z $w
echo $(( 9223372036854775807 + 1 ))
echo $(( -9223372036854775807 - 1 ))
echo $(( 3 ** 40 ))
