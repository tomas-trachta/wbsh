	const ManPage* findManPage(const std::string& name) {
		for (const ManPage& page : kManPages) {
			if (name == page.name) return &page;
		}

		return nullptr;
	}

	const ManPage* manPagesBegin() {
		return std::begin(kManPages);
	}

	const ManPage* manPagesEnd() {
		return std::end(kManPages);
	}

